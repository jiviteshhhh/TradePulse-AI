export function generateOrderBook(midPrice: number, tickSize: number): OrderBook {
  const levelsCount = 14;
  const asks: OrderBook['asks'] = [];
  const bids: OrderBook['bids'] = [];

  let askRunning = 0;
  for (let i = 0; i < levelsCount; i++) {
    const price = Number((midPrice + (i + 1) * tickSize * 2).toFixed(2));
    const size = Number((Math.random() * 2.8 + 0.4).toFixed(3));
    askRunning += size;
    asks.push({
      price,
      size,
      total: Number(askRunning.toFixed(3)),
      depthPercent: Math.min(100, Math.round((askRunning / 25) * 100)),
      ordersCount: Math.floor(Math.random() * 8) + 1,
    });
  }

  let bidRunning = 0;
  for (let i = 0; i < levelsCount; i++) {
    const price = Number((midPrice - (i + 1) * tickSize * 2).toFixed(2));
    const size = Number((Math.random() * 3.1 + 0.5).toFixed(3));
    bidRunning += size;
    bids.push({
      price,
      size,
      total: Number(bidRunning.toFixed(3)),
      depthPercent: Math.min(100, Math.round((bidRunning / 25) * 100)),
      ordersCount: Math.floor(Math.random() * 9) + 1,
    });
  }

  const bestAsk = asks[0]?.price ?? midPrice + tickSize;
  const bestBid = bids[0]?.price ?? midPrice - tickSize;
  const spread = Number((bestAsk - bestBid).toFixed(2));
  const spreadPercent = Number(((spread / midPrice) * 100).toFixed(4));

  return {
    asks,
    bids,
    spread,
    spreadPercent,
    midPrice,
    bidDepthTotal: Number(bidRunning.toFixed(2)),
    askDepthTotal: Number(askRunning.toFixed(2)),
    imbalanceRatio: Number(((bidRunning - askRunning) / (bidRunning + askRunning)).toFixed(3)),
  };
}

export function generateInitialCandles(basePrice: number): Candle[] {
  const candles: Candle[] = [];
  const count = 48;
  const now = Date.now();
  let currentClose = basePrice * 0.978;

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = now - i * 60 * 1000;
    const delta = (Math.random() - 0.48) * (basePrice * 0.0035);
    const open = currentClose;
    const close = Math.max(open + delta, 1);
    const high = Math.max(open, close) + Math.random() * (basePrice * 0.0015);
    const low = Math.min(open, close) - Math.random() * (basePrice * 0.0015);
    const volume = Math.floor(Math.random() * 45 + 12);
    const vwap = (high + low + close) / 3;

    candles.push({
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
      vwap: Number(vwap.toFixed(2)),
    });
    currentClose = close;
  }
  return candles;
}

